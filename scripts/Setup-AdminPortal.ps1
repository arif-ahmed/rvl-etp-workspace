<#
.SYNOPSIS
  Prepares (and optionally starts) a local copy of the Angular admin portal wired to Floci. Safe to re-run.

.DESCRIPTION
  The rvl-gobcb-admin-portal submodule is never touched. This script:
  1. Copies it to portal-local/admin-portal (git-ignored via .git/info/exclude; node_modules is kept between runs).
  2. Asks the running Floci for the Admin pool's PoolId and the 'etp-local' ClientId, so a Cognito reset is picked up.
  3. Writes src/environments/environment*.ts in the COPY (the submodule ships them empty; CI fills them from SSM).
  4. Points Amplify at the dev-server proxy (aws-exports.ts in the COPY) and writes proxy.conf.js:
     /p/cognito -> Floci, /p/<service> -> backend services, /p/serverless -> a local OTP stub (OTP = 123456).
  5. Enables ALLOW_USER_SRP_AUTH on the Floci app client (the portal signs in with SRP; seed-users.ps1 only enables password auth).
  6. Runs npm install when needed. With -Start it then runs ng serve on http://localhost:4200.

  Run it again after every Floci reset / re-seed (floci/seed-users.ps1), or after the submodule is updated.
#>
param(
    [switch]$Start,          # run ng serve after preparing
    [int]$Port = 4200
)
$ErrorActionPreference = 'Stop'

$root   = Split-Path $PSScriptRoot -Parent
$src    = Join-Path $root 'rvl-gobcb-admin-portal'
$dst    = Join-Path $root 'portal-local\admin-portal'
$floci  = 'http://localhost:4566'
$env:AWS_ACCESS_KEY_ID = 'test'; $env:AWS_SECRET_ACCESS_KEY = 'test'; $env:AWS_REGION = 'us-east-1'; $env:AWS_PAGER = ''

function Invoke-Aws { $out = & aws --endpoint-url $floci @args; if ($LASTEXITCODE) { throw "aws $($args -join ' ') failed" }; $out }
function Write-Text($path, $text) { [IO.File]::WriteAllText($path, $text, (New-Object Text.UTF8Encoding $false)) }

if (-not (Test-Path (Join-Path $src 'package.json'))) { throw "Submodule not checked out: $src (run: git submodule update --init rvl-gobcb-admin-portal)" }
foreach ($tool in 'aws', 'node', 'npm') { if (-not (Get-Command $tool -ErrorAction SilentlyContinue)) { throw "$tool not found on PATH" } }

# 1. Cognito IDs from Floci
try { $poolId = Invoke-Aws cognito-idp list-user-pools --max-results 60 --query "UserPools[?Name=='etp-admin'].Id | [0]" --output text }
catch { throw "Cannot reach Floci at $floci. Start it: docker compose -f floci/docker-compose.yml up -d" }
if (-not $poolId -or $poolId -eq 'None') { throw "Pool 'etp-admin' not found. Run: pwsh ./floci/seed-users.ps1" }
$clientId = Invoke-Aws cognito-idp list-user-pool-clients --user-pool-id $poolId --query "UserPoolClients[?ClientName=='etp-local'].ClientId | [0]" --output text
if (-not $clientId -or $clientId -eq 'None') { throw "Client 'etp-local' not found in $poolId. Run: pwsh ./floci/seed-users.ps1" }
Write-Host "cognito Admin pool $poolId client $clientId"

# 2. SRP on the app client (update replaces the whole list, so name every flow)
Invoke-Aws cognito-idp update-user-pool-client --user-pool-id $poolId --client-id $clientId `
    --explicit-auth-flows ALLOW_USER_PASSWORD_AUTH ALLOW_ADMIN_USER_PASSWORD_AUTH ALLOW_REFRESH_TOKEN_AUTH ALLOW_USER_SRP_AUTH | Out-Null
Write-Host 'ok  SRP enabled on app client'

# 3. Copy the portal (keep node_modules/.angular; skip .git and build output)
New-Item -ItemType Directory -Force $dst | Out-Null
robocopy $src $dst /E /XD node_modules .git .angular dist /NFL /NDL /NJH /NJS /NP | Out-Null
if ($LASTEXITCODE -ge 8) { throw "robocopy failed ($LASTEXITCODE)" }
Write-Host "ok  copied $src -> $dst"

# 4. Environment files (in the copy)
$envTs = @"
// GENERATED by scripts/Setup-AdminPortal.ps1 - do not edit, re-run the script.
export const environment = {
  production: false,
  aws: { region: 'us-east-1', userPoolId: '$poolId', userPoolWebClientId: '$clientId' },
  services: {
    admin: '/p/admin', booking: '/p/booking', ticketing: '/p/ticketing',
    userissue: '/p/userissue', userissuehub: '/p/userissue',
  },
  serverless: { baseUrl: '/p/serverless', authorization: 'local' },
  cloudFront: { cloudFrontUrl: 'http://localhost:$Port', mainDomain: 'localhost' },
};
"@
Write-Text (Join-Path $dst 'src\environments\environment.ts') $envTs
Write-Text (Join-Path $dst 'src\environments\environment.prod.ts') $envTs

# 5. Amplify endpoint override (copy only)
$awsExports = Join-Path $dst 'src\app\core\config\aws-exports.ts'
$t = Get-Content $awsExports -Raw
if ($t -notmatch 'endpoint:') {
    $t = $t -replace '(userPoolWebClientId: environment\.aws\.userPoolWebClientId,)', "`$1`r`n    endpoint: 'http://localhost:$Port/p/cognito',"
    Write-Text $awsExports $t
}

# 6. Proxy + OTP stub
$proxy = @'
// GENERATED by scripts/Setup-AdminPortal.ps1. Local-only stand-in for the "serverless" 2FA API: any phone, OTP is 123456.
const stub = (okStatus, checkOtp) => (req, res) => {
  let data = '';
  req.on('data', c => (data += c));
  req.on('end', () => {
    let status = okStatus;
    if (checkOtp) { try { if (JSON.parse(data).otp !== '123456') status = 'invalid_otp'; } catch {} }
    res.setHeader('Content-Type', 'application/json');
    res.statusCode = status === 'invalid_otp' ? 400 : 200;
    res.end(JSON.stringify({ status_message: status }));
  });
  return true;
};
const route = (p, target) => ({ target, pathRewrite: { ['^' + p]: '' }, changeOrigin: true });
module.exports = {
  '/p/cognito': route('/p/cognito', 'http://localhost:4566'),
  '/p/admin': route('/p/admin', 'http://localhost:5101'),
  '/p/booking': route('/p/booking', 'http://localhost:5102'),
  '/p/ticketing': route('/p/ticketing', 'http://localhost:5108'),
  '/p/userissue': { ...route('/p/userissue', 'http://localhost:5110'), ws: true },
  '/p/serverless/admin/login-2fa-send-otp': { target: 'http://x', bypass: (req, res) => stub('otp_generated_and_enqueued_successfully')(req, res) },
  '/p/serverless/admin/login-2fa-verify-otp': { target: 'http://x', bypass: (req, res) => stub('sms_otp_verified_successfully', true)(req, res) },
};
'@
Write-Text (Join-Path $dst 'proxy.conf.js') $proxy
Write-Host 'ok  environment.ts, aws-exports.ts, proxy.conf.js written'

# 7. Dependencies (only when missing or package.json changed)
Push-Location $dst
try {
    $stamp = Join-Path $dst 'node_modules\.pkg-hash'
    $hash  = (Get-FileHash (Join-Path $dst 'package.json')).Hash
    if (-not (Test-Path $stamp) -or (Get-Content $stamp -Raw).Trim() -ne $hash) {
        Write-Host 'npm install (first time takes a few minutes)...'
        npm install --legacy-peer-deps
        if ($LASTEXITCODE) { throw 'npm install failed' }
        Set-Content $stamp $hash
    }
    Write-Host "`nReady. Log in at http://localhost:$Port with phone 1700000001, OTP 123456, password Passw0rd!23"
    if ($Start) { npx ng serve --proxy-config proxy.conf.js --port $Port }
    else { Write-Host "Start it with:  pwsh ./scripts/Setup-AdminPortal.ps1 -Start" }
}
finally { Pop-Location }
