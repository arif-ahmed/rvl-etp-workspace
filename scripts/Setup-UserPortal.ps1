<#
.SYNOPSIS
  Prepares (and optionally starts) a local copy of the Angular user portal (ETP-Web) wired to Floci. Safe to re-run.

.DESCRIPTION
  The rvl-gobcb-user-portal submodule is never touched. This script:
  1. Copies ETP-Web to portal-local/user-portal (git-ignored; node_modules is kept between runs).
  2. Asks the running Floci for the User pool's PoolId and the 'etp-local' ClientId, so a Cognito reset is picked up.
  3. Creates src/environments/environment*.ts in the COPY (the submodule has no environments folder; CI writes it from SSM).
  4. Points Amplify at the dev-server proxy (awsConfig.ts in the COPY) and writes proxy.conf.js:
     /p/cognito -> Floci, /p/<service> -> backend services (the portal expects one gateway host, so all services share /p).
  5. Enables ALLOW_USER_SRP_AUTH on the Floci app client (the portal signs in with SRP).
  6. Runs npm install when needed. With -Start it then runs ng serve on http://localhost:4201.

  Not available locally: the "identity" API (sign-up, OTP, user/my-profile) has no source in any repo; OneID SSO needs an external provider.
  Run it again after every Floci reset / re-seed (floci/seed-users.ps1), or after the submodule is updated.
#>
param(
    [switch]$Start,          # run ng serve after preparing
    [int]$Port = 4201
)
$ErrorActionPreference = 'Stop'

$root   = Split-Path $PSScriptRoot -Parent
$src    = Join-Path $root 'rvl-gobcb-user-portal\ETP-Web'
$dst    = Join-Path $root 'portal-local\user-portal'
$floci  = 'http://localhost:4566'
$env:AWS_ACCESS_KEY_ID = 'test'; $env:AWS_SECRET_ACCESS_KEY = 'test'; $env:AWS_REGION = 'us-east-1'; $env:AWS_PAGER = ''

function Invoke-Aws { $out = & aws --endpoint-url $floci @args; if ($LASTEXITCODE) { throw "aws $($args -join ' ') failed" }; $out }
function Write-Text($path, $text) { [IO.File]::WriteAllText($path, $text, (New-Object Text.UTF8Encoding $false)) }

if (-not (Test-Path (Join-Path $src 'package.json'))) { throw "Submodule not checked out: $src (run: git submodule update --init rvl-gobcb-user-portal)" }
foreach ($tool in 'aws', 'node', 'npm') { if (-not (Get-Command $tool -ErrorAction SilentlyContinue)) { throw "$tool not found on PATH" } }

# 1. Cognito IDs from Floci
try { $poolId = Invoke-Aws cognito-idp list-user-pools --max-results 60 --query "UserPools[?Name=='etp-user'].Id | [0]" --output text }
catch { throw "Cannot reach Floci at $floci. Start it: docker compose -f floci/docker-compose.yml up -d" }
if (-not $poolId -or $poolId -eq 'None') { throw "Pool 'etp-user' not found. Run: pwsh ./floci/seed-users.ps1" }
$clientId = Invoke-Aws cognito-idp list-user-pool-clients --user-pool-id $poolId --query "UserPoolClients[?ClientName=='etp-local'].ClientId | [0]" --output text
if (-not $clientId -or $clientId -eq 'None') { throw "Client 'etp-local' not found in $poolId. Run: pwsh ./floci/seed-users.ps1" }
Write-Host "cognito User pool $poolId client $clientId"

# 2. SRP on the app client (update replaces the whole list, so name every flow)
Invoke-Aws cognito-idp update-user-pool-client --user-pool-id $poolId --client-id $clientId `
    --explicit-auth-flows ALLOW_USER_PASSWORD_AUTH ALLOW_ADMIN_USER_PASSWORD_AUTH ALLOW_REFRESH_TOKEN_AUTH ALLOW_USER_SRP_AUTH | Out-Null
Write-Host 'ok  SRP enabled on app client'

# 3. Copy the portal (keep node_modules/.angular; skip .git and build output)
New-Item -ItemType Directory -Force $dst | Out-Null
robocopy $src $dst /E /XD node_modules .git .angular dist /NFL /NDL /NJH /NJS /NP | Out-Null
if ($LASTEXITCODE -ge 8) { throw "robocopy failed ($LASTEXITCODE)" }
Write-Host "ok  copied $src -> $dst"

# 4. Environment files (in the copy). All API hosts share /p, like the single gateway host in the deployed system.
$envTs = @"
// GENERATED by scripts/Setup-UserPortal.ps1 - do not edit, re-run the script.
export const environment = {
  production: false,
  aws: {
    region: 'us-east-1',
    userPoolId: '$poolId',
    userPoolWebClientId: '$clientId',
    oauth: undefined as any,
    oneIdRegisterUrl: '',
    oneIdLogoutUrl: '',
  },
  services: {
    bookings: '/p', events: '/p', tickets: '/p',
    userissue: '/p', userissuehub: '/p',
    identity: '/p/identity',
  },
  headerkey: 'local',
  googleAnalyticsId: '',
  homePageSettings: { homeTotalEvents: 6, fourImage: 4, eventContentImage: '' },
};
"@
$envDir = Join-Path $dst 'src\environments'
New-Item -ItemType Directory -Force $envDir | Out-Null
Write-Text (Join-Path $envDir 'environment.ts') $envTs
Write-Text (Join-Path $envDir 'environment.prod.ts') $envTs

# 5. Amplify endpoint override (copy only)
$awsConfig = Join-Path $dst 'src\app\modules\core\config\awsConfig.ts'
$t = Get-Content $awsConfig -Raw
if ($t -notmatch 'endpoint:') {
    $t = $t -replace '(userPoolWebClientId: environment\.aws\.userPoolWebClientId,)', "`$1`r`n    endpoint: 'http://localhost:$Port/p/cognito',"
    Write-Text $awsConfig $t
}

# 6. Proxy
$proxy = @'
// GENERATED by scripts/Setup-UserPortal.ps1.
const route = (p, target) => ({ target, pathRewrite: { ['^' + p]: '' }, changeOrigin: true });
const svc = (name, port, extra) => ({ ['/p/' + name]: { target: 'http://localhost:' + port, pathRewrite: { '^/p': '' }, changeOrigin: true, ...extra } });
module.exports = {
  '/p/cognito': route('/p/cognito', 'http://localhost:4566'),
  ...svc('admin', 5101), ...svc('booking', 5102), ...svc('event', 5103),
  ...svc('ticketing', 5108), ...svc('userissue', 5110, { ws: true }),
  // The "identity" API (sign-up, OTP, user/my-profile) has no local implementation.
  '/p/identity': {
    target: 'http://x',
    bypass: (req, res) => {
      res.setHeader('Content-Type', 'application/json');
      res.statusCode = 503;
      res.end(JSON.stringify({ status_message: 'identity_api_not_available_locally' }));
      return true;
    },
  },
};
'@
Write-Text (Join-Path $dst 'proxy.conf.js') $proxy
Write-Host 'ok  environment.ts, awsConfig.ts, proxy.conf.js written'

# 7. Dependencies (only when missing or package.json changed)
Push-Location $dst
try {
    $stamp = Join-Path $dst 'node_modules\.pkg-hash'
    $hash  = (Get-FileHash (Join-Path $dst 'package.json')).Hash
    if (-not (Test-Path $stamp) -or (Get-Content $stamp -Raw).Trim() -ne $hash) {
        Write-Host 'npm install (first time takes a few minutes)...'
        npm install --legacy-peer-deps
        if ($LASTEXITCODE) { throw 'npm install failed' }
        Set-Content $stamp $hash
    }
    Write-Host "`nReady. Log in at http://localhost:$Port with phone 1700000011, password Passw0rd!23"
    if ($Start) { npx ng serve --proxy-config proxy.conf.js --port $Port }
    else { Write-Host "Start it with:  pwsh ./scripts/Setup-UserPortal.ps1 -Start" }
}
finally { Pop-Location }
